#!/usr/bin/env bash
# Validate scope/hotspots.tsv against every in-scope checkout and write notes/ATTACK-SURFACE.md:
# where each in-scope attack surface lives, its size per version, how much it changed between
# the two in-scope majors, and which lab exercises it.
set -euo pipefail
LAB_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
exec python3 -I - "$LAB_ROOT" <<'PY'
import csv, json, os, subprocess, sys
root = sys.argv[1]
m = json.load(open(os.path.join(root, "scope", "manifest.json")))
vmrs = [(c["dest"].split("/")[1], os.path.join(root, "src", c["dest"], "src"), c["tag"]) for c in m["checkouts"] if c["dest"].startswith("vmr/")]
rows = list(csv.DictReader(open(os.path.join(root, "scope", "hotspots.tsv")), delimiter="\t"))

def stats(path):
    if os.path.isfile(path):
        return 1, sum(1 for _ in open(path, errors="ignore"))
    files = loc = 0
    for d, _, fs in os.walk(path):
        for f in fs:
            if f.endswith((".cs", ".cpp", ".c", ".h", ".hpp", ".ts", ".js")) and "/test" not in d.lower():
                files += 1
                loc += sum(1 for _ in open(os.path.join(d, f), errors="ignore"))
    return files, loc

def changed(a, b):
    """Changed product files between the two majors (diff -rq, tests excluded)."""
    if not (os.path.exists(a) and os.path.exists(b)):
        return "n/a"
    r = subprocess.run(["diff", "-rq", "-x", "test", "-x", "tests", "-x", "*.Tests", a, b], capture_output=True, text=True)
    return str(sum(1 for l in r.stdout.splitlines() if l.strip()))

out = ["# In-scope attack surface", "",
       "Generated by `scripts/04-attack-surface.sh` from `scope/hotspots.tsv`; every path is re-checked against the checkouts on each run.",
       "Sizes count product source only (tests excluded). **Δ files** = product files that differ between " +
       " and ".join(f"`{t}`" for _, _, t in vmrs) + ": a large Δ means new code that has had little outside review.", "",
       "Known public CVEs are listed to point at bug *classes*. A re-report of a known issue is out of scope; a variant that bypasses its fix is not.", "",
       "| Area | Path (under `src/vmr/<ver>/src/`) | " + " | ".join(f"{v} files/LOC" for v, _, _ in vmrs) + " | Δ files | Bug classes | Lab coverage | Public history |",
       "|---|---|" + "---|" * len(vmrs) + "---|---|---|---|"]
missing = []
for r in rows:
    cells = []
    paths = []
    for v, base, _ in vmrs:
        p = os.path.join(base, r["path"])
        paths.append(p)
        if os.path.exists(p):
            f, loc = stats(p)
            cells.append(f"{f} / {loc:,}")
        else:
            cells.append("— absent")
            missing.append(f"{v}: {r['path']}")
    delta = changed(paths[0], paths[-1]) if len(paths) > 1 else "n/a"
    cov = r["lab_coverage"]
    cov = f"⚪ {cov}" if cov.startswith(("none", "Windows")) else f"🟢 {cov}"
    out.append(f"| {r['area']} | `{r['path']}` | " + " | ".join(cells) + f" | {delta} | {r['classes']} | {cov} | {r.get('known_public_history') or ''} |")
covered = sum(1 for r in rows if not r["lab_coverage"].startswith(("none", "Windows")))
out += ["", f"**Coverage:** {covered}/{len(rows)} areas have lab tooling; ⚪ rows are open ground.", ""]
if missing:
    out += ["### Absent in one version", ""] + [f"- `{x}`" for x in missing] + [""]
path = os.path.join(root, "notes", "ATTACK-SURFACE.md")
open(path, "w").write("\n".join(out))
print(f"wrote {path}: {len(rows)} areas, {covered} with lab coverage, {len(missing)} path(s) absent in a version")
PY
